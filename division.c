#include<stdio.h> // program to find whether a number is divisible by 5 or not.
int main() 
{
    int a;
    printf("Enter a number : ");
    scanf("%d", &a);

 if (a % 5 ==0) 
    { printf("a is divisible by 5"); }
 else
    { printf("a isn't divisible by 5"); } 
 return 0;
}   
    
